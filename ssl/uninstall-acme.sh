#!/usr/bin/env bash

set -Eeuo pipefail

###############################################################################
# acme.sh 卸载脚本
#
# 功能：
#   1. 卸载 acme.sh
#   2. 删除 acme.sh cron
#   3. 删除 /root/.acme.sh
#
# 不会删除：
#   /etc/letsencrypt
#   Docker
#   Nginx
#   Nginx 配置
#   已部署的 SSL 证书
#
# 特点：
#   - 完全非交互
#   - 可重复执行
#   - 不要求 acme.sh 当前存在
###############################################################################


###############################################################################
# 配置
###############################################################################

ACME_HOME="/root/.acme.sh"
ACME_BIN="${ACME_HOME}/acme.sh"

LETSENCRYPT_HOME="/etc/letsencrypt"


###############################################################################
# Root 检查
###############################################################################

if [[ "${EUID}" -ne 0 ]]; then
    echo "[ERROR] 请使用 root 用户运行此脚本。" >&2
    exit 1
fi


###############################################################################
# 开始
###############################################################################

echo
echo "============================================================"
echo " 卸载 acme.sh"
echo "============================================================"
echo


###############################################################################
# 使用 acme.sh 自己的卸载机制
###############################################################################

if [[ -x "${ACME_BIN}" ]]; then

    echo "[INFO] 检测到 acme.sh：${ACME_BIN}"
    echo "[INFO] 执行 acme.sh --uninstall..."

    "${ACME_BIN}" --uninstall || {
        echo "[WARN] acme.sh --uninstall 返回非 0，继续执行清理。"
    }

else

    echo "[INFO] 未检测到 acme.sh，可直接执行清理。"

fi


###############################################################################
# 清理 acme.sh cron
###############################################################################

if command -v crontab >/dev/null 2>&1; then

    echo "[INFO] 清理 acme.sh cron..."

    CRON_TMP="$(mktemp)"

    if crontab -l > "${CRON_TMP}" 2>/dev/null; then

        if grep -Fq "${ACME_HOME}" "${CRON_TMP}"; then

            grep -Fv "${ACME_HOME}" "${CRON_TMP}" \
                | crontab -

            echo "[INFO] acme.sh cron 已删除。"

        else

            echo "[INFO] 未发现 acme.sh cron。"

        fi

    else

        echo "[INFO] 当前用户没有 crontab。"

    fi

    rm -f "${CRON_TMP}"

else

    echo "[INFO] 当前系统没有 crontab 命令，跳过 cron 清理。"

fi


###############################################################################
# 删除 acme.sh 工作目录
###############################################################################

if [[ -d "${ACME_HOME}" ]]; then

    echo "[INFO] 删除：${ACME_HOME}"

    rm -rf "${ACME_HOME}"

else

    echo "[INFO] ${ACME_HOME} 不存在。"

fi


###############################################################################
# 验证 acme.sh
###############################################################################

if [[ -e "${ACME_HOME}" ]]; then

    echo "[WARN] ${ACME_HOME} 仍然存在，请手动检查。"

else

    echo "[INFO] acme.sh 已删除。"

fi


###############################################################################
# 验证 Let's Encrypt 证书目录
###############################################################################

echo
echo "[INFO] 检查现有证书目录..."

if [[ -d "${LETSENCRYPT_HOME}" ]]; then

    echo "[OK] ${LETSENCRYPT_HOME} 保留。"

    if [[ -d "${LETSENCRYPT_HOME}/live" ]]; then

        echo
        echo "现有证书："

        find "${LETSENCRYPT_HOME}/live" \
            -mindepth 1 \
            -maxdepth 1 \
            -type d \
            -print \
            2>/dev/null || true

    fi

else

    echo "[INFO] ${LETSENCRYPT_HOME} 不存在。"

fi


###############################################################################
# 完成
###############################################################################

echo
echo "============================================================"
echo " acme.sh 卸载完成"
echo "============================================================"
echo
echo "已删除："
echo "  ${ACME_HOME}"
echo "  acme.sh cron"
echo
echo "已保留："
echo "  ${LETSENCRYPT_HOME}"
echo "  SSL 证书"
echo "  Docker"
echo "  Nginx"
echo "  Nginx 配置"
echo
echo "注意："
echo "  卸载 acme.sh 后，现有证书仍可继续使用，"
echo "  但将不再自动续期。"
echo "============================================================"
echo